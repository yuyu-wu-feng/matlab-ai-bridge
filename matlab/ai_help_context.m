function context = ai_help_context(question, previousQuestions)
% Read help only for MathWorks functions on the current path. Never evaluate
% the question or read an editor document, user function or workspace value.
if nargin<2, previousQuestions=''; end
query=[char(question) ' ' char(previousQuestions)];
topics=regexp(query,'[A-Za-z][A-Za-z0-9_]*(?:\.[A-Za-z][A-Za-z0-9_]*)*','match');
aliases={ ...
    '插值',{'interp1','interp2','griddedInterpolant'}; ...
    '拟合',{'polyfit','fit','polyval'}; ...
    '阶乘',{'factorial'}; '积分',{'integral','trapz'}; ...
    '微分',{'diff','gradient'}; '导数',{'diff','gradient'}; ...
    '傅里叶',{'fft','ifft'}; '频谱',{'fft','pwelch'}; ...
    '滤波',{'filter','filtfilt','designfilt'}; ...
    '绘图',{'plot','scatter','surf'}; '画图',{'plot','scatter'}; ...
    '优化',{'fminsearch','fmincon','optimoptions'}; ...
    '方程',{'fzero','fsolve','solve'}; '微分方程',{'ode45','ode15s'}; ...
    '矩阵',{'mldivide','eig','svd'}; '表格',{'table','readtable'}; ...
    'Excel',{'readtable','readmatrix','writetable'}; ...
    '随机',{'rand','randn','rng'}; '统计',{'mean','std','median'}; ...
    '字符串',{'string','char','contains'}; '并行',{'parfor','parpool'}; ...
    '图像',{'imread','imshow','imfilter'}; '工具箱',{'ver'}; ...
    '深度学习',{'trainnet','dlnetwork'}; '机器学习',{'fitcsvm','fitctree'}};
for k=1:size(aliases,1)
    if contains(lower(query),lower(aliases{k,1})), topics=[topics aliases{k,2}]; end
end
topics=unique(topics,'stable'); topics=topics(1:min(40,numel(topics)));
docs=struct('id',{},'topic',{},'text',{});
root=lower(strrep([matlabroot filesep],'\','/'));
for k=1:numel(topics)
    topic=topics{k};
    if ismember(lower(topic),{'matlab','ai','excel'}), continue; end
    location=which(topic);
    if isempty(location) || ~contains(lower(strrep(location,'\','/')),root), continue; end
    try
        content=help(topic);
        content=regexprep(content,'<[^>]*>','');
        if isempty(strtrim(content)), continue; end
        content=content(1:min(6000,numel(content)));
        docs(end+1)=struct('id',sprintf('H%d',numel(docs)+1),'topic',topic,'text',content);
        if numel(docs)>=8, break; end
    catch
        % An unavailable help page is not evidence that a function is absent.
    end
end
products=ver;
installed=struct('name',{},'version',{});
for k=1:numel(products)
    installed(end+1)=struct('name',products(k).Name,'version',products(k).Version);
end
context=struct('release',version('-release'),'version',version, ...
    'products',installed,'documents',docs, ...
    'notice','仅检索本机可解析的 MathWorks 函数帮助；不是完整文档搜索。未命中不代表不存在。已安装不代表许可证可用。');
end
