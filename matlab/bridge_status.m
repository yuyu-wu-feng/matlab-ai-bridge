function result = bridge_status()
% Return connection metadata only; never read user source or workspace data.
result = jsonencode(struct( ...
    'release', version('-release'), ...
    'version', version, ...
    'matlabroot', matlabroot, ...
    'shared', matlab.engine.isEngineShared, ...
    'session', matlab.engine.engineName, ...
    'desktop', usejava('desktop'), ...
    'sqrt_144', sqrt(144)));
end
