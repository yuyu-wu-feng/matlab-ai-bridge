function names=ai_simulink_callbacks(target)
% Callback parameter names, excluding code-generation symbol templates that
% also happen to end in Fcn (for example CustomSymbolStrEmxFcn).
known={'PreLoadFcn','PostLoadFcn','LoadFcn','InitFcn','StartFcn','PauseFcn', ...
    'ContinueFcn','StopFcn','PreSaveFcn','PostSaveFcn','CloseFcn','OpenFcn', ...
    'CopyFcn','DeleteFcn','UndoDeleteFcn','DestroyFcn','NameChangeFcn', ...
    'ParentCloseFcn','ModelCloseFcn','ClipboardFcn','PreCopyFcn','PostCopyFcn', ...
    'PreDeleteFcn','PostDeleteFcn','PreCompileFcn','PostCompileFcn'};
params=get_param(target,'ObjectParameters');
names=sort(intersect(fieldnames(params),known));
end
